const fs = require('node:fs');
const assert = require('node:assert/strict');
const root = 'D:/.openclaw/PMO/Product_Management_dashboard_db/';
const ts = require(root + 'frontend/node_modules/typescript');
const filename = root + 'frontend/src/components/MarketingWorkspace.tsx';
const source = fs.readFileSync(filename, 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const exportsObject = {};
new Function('require', 'exports', code)(name => {
  if (name === 'react/jsx-runtime') return { jsx: (type, props) => ({ type, props }) };
  if (name === 'lucide-react') return { Megaphone: 'Megaphone' };
  if (name === './OrdersPage') return { default: 'OrdersPage' };
  throw new Error('Unexpected import ' + name);
}, exportsObject);
const catalog = JSON.parse(fs.readFileSync(root + 'backend/dashboard_catalog.json', 'utf8'));
const dashboards = Array.isArray(catalog) ? catalog : catalog.dashboards;
const { marketingTabs, isMarketingPath, MARKETING_PATH } = exportsObject;
const tabs = marketingTabs(dashboards);
assert.deepEqual(tabs.map(t => t.label), ['Ads', 'SEO', 'Email / Klaviyo', 'Content']);
assert.deepEqual(tabs.map(t => t.path), ['/ads', '/seo', '/klaviyo', '/content']);
assert.deepEqual(tabs.map(t => t.dashboard.component), ['AdsPage', 'SEOPage', 'KlaviyoPage', 'ContentPage']);
for (const tab of tabs) assert.ok(isMarketingPath(tab.path));
assert.ok(isMarketingPath(MARKETING_PATH));
assert.equal(isMarketingPath('/customer-service'), false);
assert.deepEqual(marketingTabs([]), []);
assert.deepEqual(marketingTabs(dashboards.filter(d => d.path === '/content')).map(t => t.label), ['Content']);
const shell = exportsObject.default({ tabs, children: 'existing-page' });
assert.equal(shell.props.title, 'Marketing');
assert.equal(shell.props.children, 'existing-page');
const layout = fs.readFileSync(root + 'frontend/src/components/Layout.tsx', 'utf8');
const app = fs.readFileSync(root + 'frontend/src/App.tsx', 'utf8');
assert.ok(layout.includes('isMarketingPath(item.path)) continue;'));
assert.ok(layout.includes('marketingTabs(dashboards.filter(item => canOpenDashboard(item, auth.user?.role, auth.canView)))'));
assert.equal((layout.match(/label: "Marketing"/g) || []).length, 1);
assert.equal((layout.match(/item.to === MARKETING_PATH \? onMarketingPage/g) || []).length, 2);
assert.ok(layout.includes('<MarketingWorkspace tabs={marketingSectionTabs}>{children}</MarketingWorkspace>'));
assert.ok(app.includes('marketingTabs(pages)'));
assert.ok(app.includes('<Route path={MARKETING_PATH} element={<Navigate to={marketingSectionTabs[0]?.path || "/no-access"} replace />} />'));
assert.ok(app.includes('{pages.map(item => {'));
console.log('Marketing grouping checks passed: tab order, existing components, restricted/empty menus, shared shell, sidebar highlighting and routes.');
