-- Context application tables live outside the public Data API schema.
CREATE SCHEMA IF NOT EXISTS context;
REVOKE ALL ON SCHEMA context FROM PUBLIC;

CREATE TABLE IF NOT EXISTS context.files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path TEXT NOT NULL UNIQUE, name TEXT, category TEXT, content TEXT, downloaded TEXT, last_opened TEXT, size_kb INTEGER,
    search_vector TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple'::regconfig, coalesce(name, '') || ' ' || coalesce(path, '') || ' ' || coalesce(content, ''))) STORED
);

CREATE TABLE IF NOT EXISTS context.history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT, title TEXT, content TEXT, last_visit TEXT, visits INTEGER,
    search_vector TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple'::regconfig, coalesce(title, '') || ' ' || coalesce(url, '') || ' ' || coalesce(content, ''))) STORED
);

CREATE TABLE IF NOT EXISTS context.manual (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind TEXT, payload TEXT, created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.patterns (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind TEXT, detail TEXT, seen_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.applications (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company TEXT NOT NULL, role TEXT, cv_file TEXT,
            applied_at TEXT, status TEXT DEFAULT 'applied',
            notes TEXT, url TEXT, jd TEXT, created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.interviews (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company TEXT NOT NULL, scheduled_at TEXT,
            interview_type TEXT, prep_docs TEXT, notes TEXT, created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.companies (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT UNIQUE NOT NULL, source TEXT, detected_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            uid TEXT UNIQUE, title TEXT, start_at TEXT, end_at TEXT,
            location TEXT, description TEXT, category TEXT, company TEXT,
            source TEXT, created_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_events_start ON context.events(start_at);

CREATE TABLE IF NOT EXISTS context.emails (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            uid TEXT UNIQUE, from_addr TEXT, from_name TEXT, to_addr TEXT,
            subject TEXT, body_snippet TEXT, received_at TEXT,
            category TEXT, needs_reply INTEGER DEFAULT 0, replied INTEGER DEFAULT 0,
            thread_key TEXT, source TEXT, created_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_emails_thread ON context.emails(thread_key);

CREATE INDEX IF NOT EXISTS idx_emails_needs ON context.emails(needs_reply);

CREATE TABLE IF NOT EXISTS context.promises (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            who TEXT, what TEXT, by_when TEXT, source TEXT,
            resolved INTEGER DEFAULT 0, created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT, content TEXT, source_type TEXT, source_id TEXT, metadata TEXT,
    search_vector TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple'::regconfig, coalesce(title, '') || ' ' || coalesce(content, ''))) STORED
);

CREATE TABLE IF NOT EXISTS context.activity_log (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind TEXT, target TEXT, detail TEXT, timestamp TEXT
        );

CREATE INDEX IF NOT EXISTS idx_activity_ts ON context.activity_log(timestamp DESC);

CREATE TABLE IF NOT EXISTS context.ignored_files (
            path TEXT PRIMARY KEY, ignored_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.people (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT UNIQUE NOT NULL,
            birthday TEXT,
            tags TEXT,
            last_contacted TEXT,
            source TEXT,
            created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.person_facts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            person_id INTEGER NOT NULL,
            fact TEXT,
            category TEXT,
            source TEXT,
            resolved INTEGER DEFAULT 0,
            created_at TEXT,
            FOREIGN KEY (person_id) REFERENCES context.people(id) ON DELETE CASCADE
        );

CREATE INDEX IF NOT EXISTS idx_person_facts ON context.person_facts(person_id);

CREATE TABLE IF NOT EXISTS context.spends (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            amount DOUBLE PRECISION,
            merchant TEXT,
            category TEXT,
            spent_at TEXT,
            created_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_spends_date ON context.spends(spent_at);

CREATE TABLE IF NOT EXISTS context.budgets (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            category TEXT UNIQUE NOT NULL,
            amount DOUBLE PRECISION,
            period TEXT DEFAULT 'month',
            created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.patterns_detected (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind TEXT,
            title TEXT,
            detail TEXT,
            severity TEXT,
            detected_at TEXT,
            dismissed INTEGER DEFAULT 0
        );

CREATE TABLE IF NOT EXISTS context.habits (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL UNIQUE,
            emoji TEXT DEFAULT '●',
            color TEXT DEFAULT '#8b5cf6',
            target_per_week INTEGER DEFAULT 7,
            created_at TEXT,
            archived INTEGER DEFAULT 0
        );

CREATE TABLE IF NOT EXISTS context.habit_logs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            habit_id INTEGER NOT NULL,
            date TEXT NOT NULL,
            status TEXT NOT NULL,
            note TEXT,
            created_at TEXT,
            UNIQUE(habit_id, date),
            FOREIGN KEY (habit_id) REFERENCES context.habits(id) ON DELETE CASCADE
        );

CREATE INDEX IF NOT EXISTS idx_habit_logs_habit ON context.habit_logs(habit_id);

CREATE INDEX IF NOT EXISTS idx_habit_logs_date ON context.habit_logs(date);

CREATE TABLE IF NOT EXISTS context.vault_config (
            id INTEGER PRIMARY KEY CHECK (id = 1),
            salt TEXT NOT NULL,
            recovery_salt TEXT,
            encrypted_vek TEXT,
            encrypted_vek_iv TEXT,
            recovery_encrypted_vek TEXT,
            recovery_encrypted_vek_iv TEXT,
            verifier_ciphertext TEXT,
            verifier_iv TEXT,
            created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.vault_items (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL,
            category TEXT NOT NULL,
            ciphertext TEXT NOT NULL,
            iv TEXT NOT NULL,
            created_at TEXT,
            updated_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_vault_items_category ON context.vault_items(category);

CREATE INDEX IF NOT EXISTS idx_vault_items_title ON context.vault_items(title);

CREATE TABLE IF NOT EXISTS context.subscriptions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            amount DOUBLE PRECISION NOT NULL,
            billing_cycle TEXT NOT NULL DEFAULT 'monthly',
            category TEXT DEFAULT 'entertainment',
            next_renewal TEXT NOT NULL,
            payment_method TEXT,
            auto_renew INTEGER DEFAULT 1,
            notes TEXT,
            created_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_subs_renewal ON context.subscriptions(next_renewal);

CREATE TABLE IF NOT EXISTS context.debts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            person TEXT NOT NULL,
            direction TEXT NOT NULL,
            amount DOUBLE PRECISION NOT NULL,
            due_date TEXT,
            taken_at TEXT NOT NULL,
            settled INTEGER DEFAULT 0,
            settled_at TEXT,
            description TEXT,
            notes TEXT,
            created_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_debts_person ON context.debts(person);

CREATE INDEX IF NOT EXISTS idx_debts_settled ON context.debts(settled);

CREATE TABLE IF NOT EXISTS context.journal (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            date TEXT NOT NULL UNIQUE,
            mood INTEGER DEFAULT 3,
            headline TEXT,
            content TEXT,
            tags TEXT,
            created_at TEXT,
            updated_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_journal_date ON context.journal(date);

CREATE TABLE IF NOT EXISTS context.saving_goals (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL,
            target_amount DOUBLE PRECISION NOT NULL,
            current_amount DOUBLE PRECISION DEFAULT 0,
            target_date TEXT,
            category TEXT DEFAULT 'purchase',
            emoji TEXT DEFAULT '🎯',
            is_locked INTEGER DEFAULT 0,
            notes TEXT,
            created_at TEXT
        );

CREATE TABLE IF NOT EXISTS context.users (
            id TEXT PRIMARY KEY,
            email TEXT UNIQUE NOT NULL,
            name TEXT,
            password_hash TEXT,
            avatar TEXT,
            provider TEXT DEFAULT 'email',
            role TEXT DEFAULT 'Owner',
            created_at TEXT,
            last_sign_in_at TEXT
        );

CREATE INDEX IF NOT EXISTS idx_users_email ON context.users(email);

CREATE INDEX IF NOT EXISTS idx_files_search ON context.files USING GIN(search_vector);

CREATE INDEX IF NOT EXISTS idx_history_search ON context.history USING GIN(search_vector);

CREATE INDEX IF NOT EXISTS idx_chunks_search ON context.chunks USING GIN(search_vector);

CREATE UNIQUE INDEX IF NOT EXISTS idx_people_name_nocase ON context.people(lower(name));

CREATE UNIQUE INDEX IF NOT EXISTS idx_habits_name_nocase ON context.habits(lower(name));

CREATE INDEX IF NOT EXISTS idx_files_downloaded ON context.files(downloaded DESC);

CREATE INDEX IF NOT EXISTS idx_files_category ON context.files(category);

CREATE INDEX IF NOT EXISTS idx_history_visit ON context.history(last_visit DESC);

CREATE INDEX IF NOT EXISTS idx_chunks_source ON context.chunks(source_type, source_id);

